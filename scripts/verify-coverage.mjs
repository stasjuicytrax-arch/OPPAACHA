#!/usr/bin/env node
// Coverage gate (TECH-SPEC section 6). Reads the exported HTML in out/ and
// fails when an asset from content/*.json is not on the page.
//
//   npm run build            # runs this as postbuild
//   npm run verify           # standalone, on an existing out/
//   RELEASE=1 npm run build  # production gate: no pending blocks, no TODO
//
// Assets of a block that is not built yet (content/sections.json, built:false)
// are reported as pending instead of failing, so the gate stays green while
// the page is assembled block by block. RELEASE=1 removes that allowance.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const RELEASE = process.env.RELEASE === "1";
const MARKER = "TODO_FROM_PROMOKIT";

const read = (p) => JSON.parse(readFileSync(path.join(ROOT, p), "utf8"));
const html = (() => {
  const file = path.join(ROOT, "out", "index.html");
  if (!existsSync(file)) {
    console.error("verify-coverage: out/index.html not found. Run `npm run build` first.");
    process.exit(1);
  }
  return readFileSync(file, "utf8");
})();

const { videos } = read("content/videos.json");
const { photos } = read("content/photos.json");
const tour = read("content/tour.json");
const { sections } = read("content/sections.json");
const built = new Set(sections.filter((s) => s.built).map((s) => s.id));

const rendered = (id) => new RegExp(`data-asset-id="${id}"`).test(html);
const errors = [];
const pending = [];

function check(kind, list, sectionOf, expected) {
  if (list.length !== expected) {
    errors.push(`${kind}: manifest lists ${list.length}, spec requires ${expected}`);
  }
  let ok = 0;
  for (const item of list) {
    if (rendered(item.id)) {
      ok++;
      continue;
    }
    const section = sectionOf(item);
    const line = `${kind} ${item.id} (${section}) is not on the page`;
    if (!RELEASE && !built.has(section)) pending.push(line);
    else errors.push(line);
  }
  return ok;
}

const videoOk = check("video", videos, (v) => v.section, 12);
const photoOk = check("photo", photos, () => "photo", 13);

// Tour: every date rendered, and every date complete.
let tourOk = 0;
for (const d of tour.dates) {
  const id = `T-${d.date}-${String(d.city).toLowerCase().replace(/[^a-z0-9]+/g, "-")}`;
  const missing = ["city", "venue", "status"].filter((k) => !d[k] || d[k] === MARKER);
  if (missing.length) errors.push(`tour ${id} has no ${missing.join(", ")}`);
  if (rendered(id)) tourOk++;
  else if (!RELEASE && !built.has("tour")) pending.push(`tour ${id} is not on the page`);
  else errors.push(`tour ${id} is not on the page`);
}
if (tour.status === MARKER) {
  (RELEASE ? errors : pending).push("tour: dates still wait for the PromoKit (blocker B1)");
}

// Placeholder markers in the shipped HTML.
const todoCount = html.split(MARKER).length - 1;
if (todoCount) {
  const line = `${todoCount} ${MARKER} marker(s) in out/index.html`;
  (RELEASE ? errors : pending).push(line);
}

const status = errors.length ? "FAIL" : pending.length ? "PASS (with pending blocks)" : "PASS";
const report = `# Coverage

Generated by \`scripts/verify-coverage.mjs\` on every build${RELEASE ? " (release mode)" : ""}. No timestamp, so the file only changes when coverage does.

**${status}**

| Asset | On page |
|---|---|
| Video | ${videoOk}/${videos.length} |
| Photo | ${photoOk}/${photos.length} |
| Tour dates | ${tourOk}/${tour.dates.length}${tour.status === MARKER ? " (waiting for PromoKit)" : ""} |
| ${MARKER} markers | ${todoCount} |

Built blocks: ${[...built].join(", ") || "none"}.
${errors.length ? `\n## Errors\n\n${errors.map((e) => `- ${e}`).join("\n")}\n` : ""}${pending.length ? `\n## Pending (blocks not built yet)\n\n${pending.map((e) => `- ${e}`).join("\n")}\n` : ""}`;

writeFileSync(path.join(ROOT, "COVERAGE.md"), report);
console.log(`coverage: video ${videoOk}/${videos.length}, photo ${photoOk}/${photos.length}, dates ${tourOk}/${tour.dates.length}, ${MARKER} ${todoCount} -> ${status}`);
for (const e of errors) console.error(`  x ${e}`);
if (errors.length) process.exit(1);
